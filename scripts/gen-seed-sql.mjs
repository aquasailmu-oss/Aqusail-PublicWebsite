#!/usr/bin/env node
/**
 * Generate supabase/seed.sql from src/lib/seed.ts so the local database and
 * the no-database fallback always carry the same catalogue.
 *
 *   node --experimental-strip-types scripts/gen-seed-sql.mjs
 *
 * The public site shows no prices. The price_rules rows inserted here exist
 * only so the contract test can prove anon cannot reach them. It also inserts
 * one unpublished activity and one equipment resource the views must hide.
 */
import { writeFileSync } from "node:fs";
import * as seed from "../src/lib/seed.ts";

const q = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const lines = ["-- GENERATED by scripts/gen-seed-sql.mjs from src/lib/seed.ts. Do not edit.", "begin;"];

for (const a of seed.activities) {
  lines.push(
    `insert into activities (id, name, duration_minutes, is_active, sort_order, slug, summary, description_long, hero_image, gallery, show_on_website, seo_title, seo_description, min_age, restrictions, activity_type) values (${q(a.id)}, ${q(a.name)}, ${a.duration_minutes}, true, ${a.sort_order}, ${q(a.slug)}, ${q(a.summary)}, ${q(a.description)}, ${q(a.hero_image)}, ${j(a.gallery)}, true, ${q(a.seo_title)}, ${q(a.seo_description)}, ${a.min_age ?? "null"}, ${q(a.restrictions)}, ${q(a.activity_type)});`,
  );
}
// decoy: an activity that is not published
lines.push(
  `insert into activities (id, name, duration_minutes, slug, show_on_website) values ('a1000000-0000-4000-8000-0000000000ff', 'Unpublished test activity', 30, 'unpublished-test', false);`,
);

for (const p of seed.packages) {
  lines.push(
    `insert into packages (id, name, is_active, sort_order, slug, summary, description_long, hero_image, gallery, show_on_website, seo_title, seo_description, departs, returns) values (${q(p.id)}, ${q(p.name)}, true, ${p.sort_order}, ${q(p.slug)}, ${q(p.summary)}, ${q(p.description)}, ${q(p.hero_image)}, ${j(p.gallery)}, true, ${q(p.seo_title)}, ${q(p.seo_description)}, ${q(p.departs)}, ${q(p.returns)});`,
  );
  p.included_activities.forEach((a, i) =>
    lines.push(`insert into package_activities (package_id, activity_id, position) values (${q(p.id)}, ${q(a.id)}, ${i});`),
  );
}

for (const r of seed.resources) {
  lines.push(
    `insert into resources (id, name, kind, capacity, is_active, sort_order, slug, summary, description_long, hero_image, gallery, show_on_website, seo_title, seo_description, length_m, specs, charter_terms) values (${q(r.id)}, ${q(r.name)}, 'vessel', ${r.capacity}, true, ${r.sort_order}, ${q(r.slug)}, ${q(r.summary)}, ${q(r.description)}, ${q(r.hero_image)}, ${j(r.gallery)}, true, ${q(r.seo_title)}, ${q(r.seo_description)}, ${r.length_m}, ${j(r.specs)}, ${r.charter_terms ? j(r.charter_terms) : "null"});`,
  );
  for (const aid of r.serves_activity_ids)
    lines.push(`insert into resource_activities (resource_id, activity_id) values (${q(r.id)}, ${q(aid)});`);
}
// decoy: equipment is never public
lines.push(`insert into resources (name, kind, capacity, slug, show_on_website) values ('Parasail winch', 'equipment', 1, 'parasail-winch', true);`);

lines.push(`insert into tour_operators (id, name, commission_pct) values ('d4000000-0000-4000-8000-000000000001', 'Test Operator Ltd', 20);`);
const cur = `current_date - 30, current_date + 365`;
for (const [type, rows] of [["activity", seed.activities], ["package", seed.packages]]) {
  for (const row of rows) {
    for (const [channel, rate, band, cents] of [["walk_in", "retail", "adult", 100000], ["walk_in", "retail", "child", 60000], ["operator", "net", "adult", 70000]]) {
      lines.push(
        `insert into price_rules (target_type, target_id, channel, rate_type, age_band, amount_cents, valid_from, valid_to) values ('${type}', ${q(row.id)}, '${channel}', '${rate}', '${band}', ${cents}, ${cur});`,
      );
    }
  }
}
lines.push(`insert into clients (name, email) values ('Private Client', 'private@example.com');`, "commit;", "");

writeFileSync("supabase/seed.sql", lines.join("\n"));
console.log(`supabase/seed.sql: ${lines.length} lines`);
